import React, { useEffect, useState } from 'react';
import axios from 'axios';

// ─── Transform our coupon documents to the shape this page expects ────────────
// Our model:   { _id, code, discountPercent, isRedeemed, redeemedAt, expiresAt, createdAt, sessionId }
// Page expects: { _id, code, discountPercent, isUsed,     generatedFor, expiresAt, createdAt }
function mapCoupon(c) {
  const gender   = c.sessionId?.detectedGender;
  const ageGroup = c.sessionId?.detectedAge;
  return {
    ...c,
    isUsed:       c.isRedeemed ?? false,
    generatedFor: gender ? `${gender} · ${ageGroup}` : 'Kiosk User',
  };
}

// ─── CouponsPage (original UI untouched) ─────────────────────────────────────
export default function CouponsPage() {
  const [coupons, setCoupons] = useState([]);
  const [loading, setLoading] = useState(true);
  const [filter,  setFilter]  = useState('all');

  useEffect(() => {
    // Changed: was BACKEND/api/coupons with r.data — now our real endpoint with r.data.data
    axios.get('/api/coupons')
      .then(r => setCoupons((r.data.data || []).map(mapCoupon)))
      .catch(() => setCoupons([]))
      .finally(() => setLoading(false));
  }, []);

  const handleMarkUsed = async (id) => {
    try {
      await axios.put(`/api/coupons/${id}/use`);
      setCoupons(prev => prev.map(c =>
        c._id === id ? { ...c, isUsed: true, isRedeemed: true, redeemedAt: new Date().toISOString() } : c
      ));
    } catch {
      alert('Failed to mark coupon as used.');
    }
  };

  const handleCollectHamper = async (id) => {
    try {
      await axios.put(`/api/coupons/${id}/collect-hamper`);
      setCoupons(prev => prev.map(c =>
        c._id === id ? { ...c, hamperCollected: true, hamperCollectedAt: new Date().toISOString() } : c
      ));
    } catch {
      alert('Failed to mark hamper as collected.');
    }
  };

  const now = new Date();
  const filtered = coupons.filter(c => {
    if (filter === 'used')    return c.isUsed;
    if (filter === 'active')  return !c.isUsed && (!c.expiresAt || new Date(c.expiresAt) > now);
    if (filter === 'expired') return !c.isUsed && c.expiresAt && new Date(c.expiresAt) <= now;
    if (filter === 'hamper')  return c.hamperEligible;
    return true;
  });

  const stats = {
    total:   coupons.length,
    used:    coupons.filter(c => c.isUsed).length,
    active:  coupons.filter(c => !c.isUsed && (!c.expiresAt || new Date(c.expiresAt) > now)).length,
    expired: coupons.filter(c => !c.isUsed && c.expiresAt && new Date(c.expiresAt) <= now).length,
    hamper:  coupons.filter(c => c.hamperEligible && !c.hamperCollected).length,
  };

  const getStatus = (c) => {
    if (c.isUsed) return { label: 'Used',    color: '#475569', bg: 'rgba(71,85,105,0.15)' };
    if (c.expiresAt && new Date(c.expiresAt) <= now) return { label: 'Expired', color: '#ef4444', bg: 'rgba(239,68,68,0.1)' };
    return { label: 'Active', color: '#10b981', bg: 'rgba(16,185,129,0.1)' };
  };

  const discountColor = (pct) => {
    if (pct >= 30) return '#ffd700';
    if (pct >= 20) return '#10b981';
    return '#3b82f6';
  };

  return (
    <div style={{ padding: '30px 36px' }}>
      <div className="db-page-header" style={{ padding: 0, marginBottom: 28 }}>
        <h1 className="db-page-title">Coupons</h1>
        <p className="db-page-sub">All discount codes generated by the kiosk</p>
      </div>

      {/* Stats */}
      <div style={{ display: 'grid', gridTemplateColumns: 'repeat(5,1fr)', gap: 14, marginBottom: 24 }}>
        {[
          { label: 'Total',        value: stats.total,   color: '#3b82f6', id: 'all'     },
          { label: 'Active',       value: stats.active,  color: '#10b981', id: 'active'  },
          { label: 'Used',         value: stats.used,    color: '#8b5cf6', id: 'used'    },
          { label: 'Expired',      value: stats.expired, color: '#f97316', id: 'expired' },
          { label: 'Gift Hampers Pending', value: stats.hamper, color: '#f59e0b', id: 'hamper' },
        ].map(s => (
          <div key={s.id} onClick={() => setFilter(s.id)} style={{
            padding: '18px 20px',
            background: filter === s.id ? `rgba(255,255,255,0.09)` : 'rgba(255,255,255,0.05)',
            backdropFilter: 'blur(24px)', WebkitBackdropFilter: 'blur(24px)',
            border: `1px solid ${filter === s.id ? s.color + '55' : 'rgba(255,255,255,0.1)'}`,
            borderRadius: 12, cursor: 'pointer', transition: 'all 0.18s',
            boxShadow: filter === s.id ? `0 0 28px ${s.color}28, 0 0 8px ${s.color}14` : 'none',
          }}>
            <div style={{ fontSize: '1.6rem', fontWeight: 800, color: s.color, marginBottom: 4, fontFamily: 'var(--font-mono)' }}>{s.value}</div>
            <div style={{ fontSize: '0.8rem', color: 'var(--text-secondary)' }}>{s.label === 'Gift Hampers Pending' ? s.label : `${s.label} Coupons`}</div>
          </div>
        ))}
      </div>

      {/* Table */}
      {loading ? (
        <div style={{ textAlign: 'center', padding: 60, color: 'var(--text-muted)' }}>Loading coupons...</div>
      ) : (
        <div className="db-table-card">
          {filtered.length === 0 ? (
            <div style={{ padding: 60, textAlign: 'center', color: 'var(--text-muted)' }}>No coupons found for this filter.</div>
          ) : (
            <table style={{ width: '100%', borderCollapse: 'collapse' }}>
              <thead>
                <tr style={{ borderBottom: '1px solid var(--border)' }}>
                  {['Code','Discount','Generated For','Game','Status','Gift Hamper','Expires','Created'].map(h => (
                    <th key={h} style={{ padding: '13px 18px', textAlign: 'left', fontSize: '0.72rem', fontWeight: 600, color: 'var(--text-muted)', letterSpacing: '0.08em' }}>{h.toUpperCase()}</th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {filtered.map((c, i) => {
                  const st      = getStatus(c);
                  const expired = !c.isUsed && !!c.expiresAt && new Date(c.expiresAt) <= now;
                  return (
                    <tr key={c._id || i} style={{ borderBottom: '1px solid rgba(255,255,255,0.03)' }}
                      onMouseEnter={e => e.currentTarget.style.background='rgba(255,255,255,0.02)'}
                      onMouseLeave={e => e.currentTarget.style.background='transparent'}>
                      <td style={{ padding: '13px 18px', fontFamily: 'var(--font-mono)', fontSize: '0.88rem', fontWeight: 600, color: 'var(--text-primary)', letterSpacing: '0.05em' }}>{c.code}</td>
                      <td style={{ padding: '13px 18px' }}>
                        <span style={{ fontFamily: 'var(--font-mono)', fontWeight: 700, fontSize: '0.95rem', color: discountColor(c.discountPercent) }}>{c.discountPercent}%</span>
                      </td>
                      <td style={{ padding: '13px 18px', fontSize: '0.82rem', color: 'var(--text-secondary)', textTransform: 'capitalize' }}>
                        {c.generatedFor}
                      </td>
                      <td style={{ padding: '13px 18px', fontSize: '0.8rem', color: 'var(--text-secondary)' }}>
                        {c.gameType === 'catch-gifts'
                          ? <span>🎁 Catch{typeof c.gameScore === 'number' ? ` · ${c.gameScore} caught` : ''}</span>
                          : <span>🎡 Spin</span>}
                      </td>
                      <td style={{ padding: '13px 18px' }}>
                        <div style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
                          <span style={{ padding: '3px 10px', borderRadius: 20, fontSize: '0.75rem', fontWeight: 600, background: st.bg, color: st.color }}>{st.label}</span>
                          {!c.isUsed && !expired && (
                            <button
                              onClick={() => handleMarkUsed(c._id)}
                              style={{ padding: '3px 8px', borderRadius: 6, fontSize: '0.7rem', fontWeight: 600, background: 'rgba(16,185,129,0.1)', border: '1px solid rgba(16,185,129,0.25)', color: '#10b981', cursor: 'pointer' }}
                            >
                              Mark Used
                            </button>
                          )}
                        </div>
                      </td>
                      <td style={{ padding: '13px 18px' }}>
                        {!c.hamperEligible ? (
                          <span style={{ color: 'var(--text-muted)', fontSize: '0.8rem' }}>—</span>
                        ) : c.hamperCollected ? (
                          <span style={{ padding: '3px 10px', borderRadius: 20, fontSize: '0.75rem', fontWeight: 600, background: 'rgba(16,185,129,0.1)', color: '#10b981' }}>✓ Collected</span>
                        ) : (
                          <div style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
                            <span style={{ padding: '3px 10px', borderRadius: 20, fontSize: '0.75rem', fontWeight: 600, background: 'rgba(245,158,11,0.12)', color: '#f59e0b' }}>🎁 Pending</span>
                            <button
                              onClick={() => handleCollectHamper(c._id)}
                              style={{ padding: '3px 8px', borderRadius: 6, fontSize: '0.7rem', fontWeight: 600, background: 'rgba(245,158,11,0.1)', border: '1px solid rgba(245,158,11,0.3)', color: '#f59e0b', cursor: 'pointer' }}
                            >
                              Mark Collected
                            </button>
                          </div>
                        )}
                      </td>
                      <td style={{ padding: '13px 18px', fontSize: '0.8rem', color: 'var(--text-muted)' }}>
                        {c.expiresAt ? new Date(c.expiresAt).toLocaleString() : 'No expiry'}
                      </td>
                      <td style={{ padding: '13px 18px', fontSize: '0.8rem', color: 'var(--text-muted)' }}>
                        {c.createdAt ? new Date(c.createdAt).toLocaleString() : '—'}
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          )}
        </div>
      )}
    </div>
  );
}
