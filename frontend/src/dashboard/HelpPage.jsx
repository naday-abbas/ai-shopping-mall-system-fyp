function GuideCard({ item, isOpen, onToggle }) {
  const { Icon, color, title, summary, body } = item;
  return (
    <div
      className="db-chart-card"
      style={{ cursor: 'pointer', transition: 'border-color 0.15s' }}
      onClick={onToggle}
    >
      <div style={{ display: 'flex', alignItems: 'center', gap: 14 }}>
        <div style={{
          width: 38, height: 38, borderRadius: 10, flexShrink: 0,
          background: `${color}22`, border: `1px solid ${color}44`,
          display: 'flex', alignItems: 'center', justifyContent: 'center',
        }}>
          <Icon size={18} color={color} strokeWidth={2} />
        </div>
        <div style={{ flex: 1, minWidth: 0 }}>
          <div className="db-chart-title" style={{ marginBottom: 2 }}>{title}</div>
          <div className="db-chart-sub" style={{ marginBottom: 0 }}>{summary}</div>
        </div>
        <ChevronDown
          size={18}
          color="rgba(255,255,255,0.35)"
          style={{ transition: 'transform 0.2s', transform: isOpen ? 'rotate(180deg)' : 'rotate(0)', flexShrink: 0 }}
        />
      </div>

      {isOpen && (
        <ul style={{
          margin: '16px 0 0', paddingLeft: 20, display: 'flex', flexDirection: 'column', gap: 9,
          borderTop: '1px solid rgba(255,255,255,0.08)', paddingTop: 16,
        }}>
          {body.map((line, i) => (
            <li key={i} style={{ color: 'rgba(255,255,255,0.65)', fontSize: '0.85rem', lineHeight: 1.55 }}>
              {line}
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}

