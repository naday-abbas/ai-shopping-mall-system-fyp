import React, { useEffect, useState } from 'react';
import axios from 'axios';

const BACKEND = process.env.REACT_APP_BACKEND_URL || 'http://localhost:5000';

const MOCK_COUPONS = Array.from({ length: 12 }, (_, i) => ({
  _id: `c${i}`,
  code: `MALL-${Math.random().toString(36).slice(2,10).toUpperCase()}`,
  discountPercent: [10,15,20,25,30,40][Math.floor(Math.random()*6)],
  isUsed: Math.random()>0.6,
  generatedFor: { gender: ['male','female'][i%2], ageGroup: ['adult','teen','child','senior'][i%4] },
  expiresAt: new Date(Date.now() + (Math.random()-0.3)*24*3600000).toISOString(),
  createdAt: new Date(Date.now() - Math.random()*48*3600000).toISOString(),
}));

export default function CouponsPage() {
  const [coupons, setCoupons] = useState([]);
  const [loading, setLoading] = useState(true);
  const [filter, setFilter] = useState('all'); // 'all' | 'used' | 'active' | 'expired'

  useEffect(() => {
    axios.get(`${BACKEND}/api/coupons`)
      .then(r => setCoupons(r.data))
      .catch(() => setCoupons(MOCK_COUPONS))
      .finally(() => setLoading(false));
  }, []);

  const now = new Date();
  const filtered = coupons.filter(c => {
    if (filter === 'used') return c.isUsed;
    if (filter === 'active') return !c.isUsed && (!c.expiresAt || new Date(c.expiresAt) > now);
    if (filter === 'expired') return !c.isUsed && c.expiresAt && new Date(c.expiresAt) <= now;
    return true;
  });

  const stats = {
    total: coupons.length,
    used: coupons.filter(c => c.isUsed).length,
    active: coupons.filter(c => !c.isUsed && (!c.expiresAt || new Date(c.expiresAt) > now)).length,
    expired: coupons.filter(c => !c.isUsed && c.expiresAt && new Date(c.expiresAt) <= now).length,
  };

  const getStatus = (c) => {
    if (c.isUsed) return { label: 'Used', color: '#475569', bg: 'rgba(71,85,105,0.15)' };
    if (c.expiresAt && new Date(c.expiresAt) <= now) return { label: 'Expired', color: '#ef4444', bg: 'rgba(239,68,68,0.1)' };
    return { label: 'Active', color: '#10b981', bg: 'rgba(16,185,129,0.1)' };
  };

  const discountColor = (pct) => {
    if (pct >= 30) return '#ffd700';
    if (pct >= 20) return '#10b981';
    return '#3b82f6';
  };

  return (
    <div style={{ padding: '32px 36px' }}>
      <div style={{ marginBottom: 28 }}>
        <h1 style={{ fontSize: '1.6rem', fontWeight: 800, marginBottom: 4 }}>Coupons</h1>
        <p style={{ color: 'var(--text-secondary)', fontSize: '0.9rem' }}>All discount codes generated by the kiosk</p>
      </div>

      {/* Stats */}
      <div style={{ display: 'grid', gridTemplateColumns: 'repeat(4,1fr)', gap: 14, marginBottom: 24 }}>
        {[
          { label: 'Total', value: stats.total, color: '#3b82f6', id: 'all' },
          { label: 'Active', value: stats.active, color: '#10b981', id: 'active' },
          { label: 'Used', value: stats.used, color: '#8b5cf6', id: 'used' },
          { label: 'Expired', value: stats.expired, color: '#f97316', id: 'expired' },
        ].map(s => (
          <div key={s.id} onClick={() => setFilter(s.id)} style={{
            padding: '18px 20px', background: 'var(--bg-card)',
            border: `1px solid ${filter === s.id ? s.color + '40' : 'var(--border)'}`,
            borderRadius: 10, cursor: 'pointer', transition: 'all 0.15s',
            boxShadow: filter === s.id ? `0 0 16px ${s.color}20` : 'none',
          }}>
            <div style={{ fontSize: '1.6rem', fontWeight: 800, color: s.color, marginBottom: 4, fontFamily: 'var(--font-mono)' }}>{s.value}</div>
            <div style={{ fontSize: '0.8rem', color: 'var(--text-secondary)' }}>{s.label} Coupons</div>
          </div>
        ))}
      </div>

      {/* Table */}
      {loading ? (
        <div style={{ textAlign: 'center', padding: 60, color: 'var(--text-muted)' }}>Loading coupons...</div>
      ) : (
        <div style={{ background: 'var(--bg-card)', border: '1px solid var(--border)', borderRadius: 12, overflow: 'hidden' }}>
          {filtered.length === 0 ? (
            <div style={{ padding: 60, textAlign: 'center', color: 'var(--text-muted)' }}>No coupons found for this filter.</div>
          ) : (
            <table style={{ width: '100%', borderCollapse: 'collapse' }}>
              <thead>
                <tr style={{ borderBottom: '1px solid var(--border)' }}>
                  {['Code','Discount','Generated For','Status','Expires','Created'].map(h => (
                    <th key={h} style={{ padding: '13px 18px', textAlign: 'left', fontSize: '0.72rem', fontWeight: 600, color: 'var(--text-muted)', letterSpacing: '0.08em' }}>{h.toUpperCase()}</th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {filtered.map((c, i) => {
                  const st = getStatus(c);
                  return (
                    <tr key={c._id || i} style={{ borderBottom: '1px solid rgba(255,255,255,0.03)' }}
                      onMouseEnter={e => e.currentTarget.style.background='rgba(255,255,255,0.02)'}
                      onMouseLeave={e => e.currentTarget.style.background='transparent'}>
                      <td style={{ padding: '13px 18px', fontFamily: 'var(--font-mono)', fontSize: '0.88rem', fontWeight: 600, color: 'var(--text-primary)', letterSpacing: '0.05em' }}>{c.code}</td>
                      <td style={{ padding: '13px 18px' }}>
                        <span style={{ fontFamily: 'var(--font-mono)', fontWeight: 700, fontSize: '0.95rem', color: discountColor(c.discountPercent) }}>{c.discountPercent}%</span>
                      </td>
                      <td style={{ padding: '13px 18px', fontSize: '0.82rem', color: 'var(--text-secondary)', textTransform: 'capitalize' }}>
                        {c.generatedFor?.gender} · {c.generatedFor?.ageGroup}
                      </td>
                      <td style={{ padding: '13px 18px' }}>
                        <span style={{ padding: '3px 10px', borderRadius: 20, fontSize: '0.75rem', fontWeight: 600, background: st.bg, color: st.color }}>{st.label}</span>
                      </td>
                      <td style={{ padding: '13px 18px', fontSize: '0.8rem', color: 'var(--text-muted)' }}>
                        {c.expiresAt ? new Date(c.expiresAt).toLocaleString() : 'No expiry'}
                      </td>
                      <td style={{ padding: '13px 18px', fontSize: '0.8rem', color: 'var(--text-muted)' }}>
                        {c.createdAt ? new Date(c.createdAt).toLocaleString() : '—'}
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          )}
        </div>
      )}
    </div>
  );
}
